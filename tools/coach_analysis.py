#!/usr/bin/env python3
"""Summarize Stockfish coaching logs and locate repeated strategic mistakes.

This script reads the CSV generated by tools/stockfish_coach.py and reports the
most common blunders and their patterns without modifying the engine.
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter, defaultdict
from pathlib import Path


def summarize_csv(path: Path) -> dict[str, object]:
    rows: list[dict[str, object]] = []
    with path.open("r", newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            rows.append(row)

    best_moves = Counter()
    loss_by_move = defaultdict(int)
    loss_by_color = defaultdict(int)
    by_fen: defaultdict[str, list[dict[str, object]]] = defaultdict(list)

    for row in rows:
        move = str(row["played"])
        best = str(row["best"])
        loss = int(float(row["loss_cp"]))
        fen = str(row["fen"])
        color = str(row["color"])
        best_moves[move] += 1
        loss_by_move[move] += loss
        loss_by_color[color] += loss
        by_fen[fen].append(row)

    most_common = best_moves.most_common(10)
    top_moves = sorted(loss_by_move.items(), key=lambda item: item[1], reverse=True)[:10]
    top_fens = sorted(by_fen.items(), key=lambda item: sum(int(float(m["loss_cp"])) for m in item[1]), reverse=True)[:10]

    return {
        "total_rows": len(rows),
        "common_moves": [{"move": move, "count": count} for move, count in most_common],
        "largest_loss_moves": [{"move": move, "total_loss_cp": total_loss} for move, total_loss in top_moves],
        "largest_loss_positions": [
            {
                "fen": fen,
                "samples": len(items),
                "total_loss_cp": sum(int(float(item["loss_cp"])) for item in items),
                "top_move": max(items, key=lambda item: int(float(item["loss_cp"]))) ["played"],
            }
            for fen, items in top_fens
        ],
        "per_color_loss": {color: total for color, total in sorted(loss_by_color.items())},
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", type=Path, help="CSV file with Stockfish coaching review rows")
    parser.add_argument("--json", type=Path, help="Optional output file for structured summary")
    args = parser.parse_args()

    summary = summarize_csv(args.csv)
    print(
        f"Total reviewed moves: {summary['total_rows']}\n"
        f"Most common bot mistakes: {summary['common_moves'][:5]}\n"
        f"Largest cumulative losses by move: {summary['largest_loss_moves'][:5]}\n"
        f"Side losses: {summary['per_color_loss']}"
    )

    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"Saved structured summary to {args.json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
